'use client'

import { useState, useEffect } from 'react'
import { generateInvoiceNumber } from '@/utils/invoiceNumber'
import { useEmailTemplates } from '@/contexts/EmailTemplateContext'

interface Project {
  id: string;
  name: string;
  type: 'farm' | 'prime' | 'new';
  status: 'active' | 'completed' | 'pending';
  client: string;
  amount: number;
}

interface BillingItem {
  id: string;
  summary: string;
  unitPrice: number;
  quantity: number;
  amount: number;
  remarks: string;
}

interface BillingCreateModalProps {
  isOpen: boolean;
  onClose: () => void;
  selectedProject?: Project;
  projects: Project[];
  onBillingApplicationComplete?: (billingData: any) => void;
}

export default function BillingCreateModal({ 
  isOpen, 
  onClose, 
  selectedProject, 
  projects,
  onBillingApplicationComplete
}: BillingCreateModalProps) {
  const [activeTab, setActiveTab] = useState<'billing' | 'email'>('billing');
  const [showFinalConfirm, setShowFinalConfirm] = useState(false);
  const [showErrorModal, setShowErrorModal] = useState(false);
  const [errorMessages, setErrorMessages] = useState<string[]>([]);
  const [applicantComment, setApplicantComment] = useState('');
  const [formData, setFormData] = useState({
    projectId: selectedProject?.id || '',
    projectName: selectedProject?.name || '',
    clientName: selectedProject?.client || '',
    billingNumber: '',
    billingDate: new Date().toISOString().split('T')[0],
    dueDate: '',
    taxRate: 10,
    notes: '',
    emailContent: {
      subject: '',
      body: '',
      to: '',
      cc: '',
      bcc: ''
    },
    items: [
      {
        id: '1',
        summary: '',
        unitPrice: 0,
        quantity: 1,
        amount: 0,
        remarks: ''
      }
    ] as BillingItem[]
  });

  const [projectSelectionMode, setProjectSelectionMode] = useState<'existing' | 'new'>(
    selectedProject ? 'existing' : 'new'
  );
  const [showProjectList, setShowProjectList] = useState(false);

  // EmailTemplateContextを使用
  const { templates } = useEmailTemplates();

  // 初期フォームデータを生成する関数
  const getInitialFormData = (project?: Project) => {
    const autoGeneratedInvoiceNumber = project ? generateInvoiceNumber(
      project.type,
      project.client,
      new Date()
    ) : '';

    return {
      projectId: project?.id || '',
      projectName: project?.name || '',
      clientName: project?.client || '',
      billingNumber: autoGeneratedInvoiceNumber,
      billingDate: new Date().toISOString().split('T')[0],
      dueDate: '',
      taxRate: 10,
      notes: '',
      emailContent: {
        subject: '',
        body: '',
        to: '',
        cc: '',
        bcc: ''
      },
      items: [
        {
          id: '1',
          summary: '',
          unitPrice: 0,
          quantity: 1,
          amount: 0,
          remarks: ''
        }
      ] as BillingItem[]
    };
  };

  useEffect(() => {
    if (isOpen) {
      // モーダルが開かれるたびにフォームデータをリセット
      const initialData = getInitialFormData(selectedProject);
      setFormData(initialData);
      setActiveTab('billing');
      setShowFinalConfirm(false);
      setShowErrorModal(false);
      setErrorMessages([]);
      setApplicantComment('');
      setProjectSelectionMode(selectedProject ? 'existing' : 'new');
      setShowProjectList(false);
    }
  }, [isOpen, selectedProject]);

  useEffect(() => {
    if (selectedProject && isOpen) {
      const autoGeneratedInvoiceNumber = generateInvoiceNumber(
        selectedProject.type,
        selectedProject.client,
        new Date()
      );
      
      setFormData(prev => ({
        ...prev,
        projectId: selectedProject.id,
        projectName: selectedProject.name,
        clientName: selectedProject.client,
        amount: selectedProject.amount,
        billingNumber: autoGeneratedInvoiceNumber
      }));
      setProjectSelectionMode('existing');
    }
  }, [selectedProject, isOpen]);

  const handleInputChange = (field: string, value: string | number | any) => {
    setFormData(prev => ({
      ...prev,
      [field]: value
    }));
  };

  const addBillingItem = () => {
    const newItem: BillingItem = {
      id: Date.now().toString(),
      summary: '',
      unitPrice: 0,
      quantity: 1,
      amount: 0,
      remarks: ''
    };
    setFormData(prev => ({
      ...prev,
      items: [...prev.items, newItem]
    }));
  };

  const removeBillingItem = (itemId: string) => {
    if (formData.items.length > 1) {
      setFormData(prev => ({
        ...prev,
        items: prev.items.filter(item => item.id !== itemId)
      }));
    }
  };

  const calculateItemAmount = (item: BillingItem) => {
    return item.unitPrice * item.quantity;
  };

  const updateBillingItem = (itemId: string, field: keyof BillingItem, value: string | number) => {
    setFormData(prev => ({
      ...prev,
      items: prev.items.map(item => {
        if (item.id === itemId) {
          const updatedItem = { ...item, [field]: value };
          if (field === 'unitPrice' || field === 'quantity') {
            updatedItem.amount = calculateItemAmount(updatedItem);
          }
          return updatedItem;
        }
        return item;
      })
    }));
  };

  const handleProjectSelect = (project: Project) => {
    const autoGeneratedInvoiceNumber = generateInvoiceNumber(
      project.type,
      project.client,
      new Date()
    );
    
    setFormData(prev => ({
      ...prev,
      projectId: project.id,
      projectName: project.name,
      clientName: project.client,
      amount: project.amount,
      billingNumber: autoGeneratedInvoiceNumber
    }));
    setProjectSelectionMode('existing');
    setShowProjectList(false);
  };

  const calculateSubtotal = () => {
    return formData.items.reduce((sum, item) => sum + calculateItemAmount(item), 0);
  };

  const calculateTaxAmount = () => {
    return Math.round(calculateSubtotal() * (formData.taxRate / 100));
  };

  const calculateTotalAmount = () => {
    return calculateSubtotal() + calculateTaxAmount();
  };

  const formatCurrency = (amount: number) => {
    return new Intl.NumberFormat('ja-JP', {
      style: 'currency',
      currency: 'JPY'
    }).format(amount);
  };

  const getCurrentUser = () => {
    return {
      name: '田中太郎',
      email: 'tanaka@festal.co.jp',
      department: '営業部'
    };
  };

  const generateEmailContent = () => {
    const currentUser = getCurrentUser();
    const totalAmount = calculateTotalAmount();
    
    return {
      subject: `【${formData.clientName}】請求書の件`,
      body: `${formData.clientName} 担当者様

平素より格別のご高配を賜り、厚く御礼申し上げます。

この度、${formData.projectName}に関する請求書を発行いたしましたので、ご連絡申し上げます。

【請求書詳細】
請求書番号: ${formData.billingNumber}
請求日: ${formData.billingDate}
請求金額: ${formatCurrency(totalAmount)}（税込）

【請求内容】
${formData.items.map(item => `・${item.summary}: ${formatCurrency(calculateItemAmount(item))}`).join('\n')}

合計金額: ${formatCurrency(totalAmount)}（税込）

請求書の詳細は添付ファイルをご確認ください。

ご不明な点がございましたら、お気軽にお問い合わせください。

今後ともよろしくお願いいたします。

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
株式会社フェスタル
担当: ${currentUser.name}
TEL: 03-1234-5678
Email: ${currentUser.email}`,
      to: `${formData.clientName.toLowerCase().replace(/\s+/g, '')}@example.com`,
      cc: formData.emailContent.cc,
      bcc: formData.emailContent.bcc
    };
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    setActiveTab('email');
  };

  const handleTemplateSelect = (template: any) => {
    const generatedContent = generateEmailContent();
    setFormData(prev => ({
      ...prev,
      emailContent: {
        subject: template.subject.replace('{clientName}', formData.clientName),
        body: template.body
          .replace('{clientName}', formData.clientName)
          .replace('{projectName}', formData.projectName)
          .replace('{billingNumber}', formData.billingNumber)
          .replace('{billingDate}', formData.billingDate)
          .replace('{totalAmount}', formatCurrency(calculateTotalAmount()))
          .replace('{items}', formData.items.map(item => `・${item.summary}: ${formatCurrency(calculateItemAmount(item))}`).join('\n'))
          .replace('{userName}', getCurrentUser().name)
          .replace('{userEmail}', getCurrentUser().email),
        to: generatedContent.to,
        cc: formData.emailContent.cc,
        bcc: formData.emailContent.bcc
      }
    }));
  };

  // バリデーション関数
  const validateForm = (): { isValid: boolean; errors: string[] } => {
    const errors: string[] = [];

    // 請求内容のバリデーション
    if (activeTab === 'billing') {
      if (!formData.projectName.trim()) {
        errors.push('案件名は必須項目です');
      }
      if (!formData.clientName.trim()) {
        errors.push('クライアント名は必須項目です');
      }
      if (!formData.billingNumber.trim()) {
        errors.push('請求書番号は必須項目です');
      }
      if (!formData.billingDate) {
        errors.push('請求日は必須項目です');
      }
      
      // 請求項目のバリデーション
      formData.items.forEach((item, index) => {
        if (!item.summary.trim()) {
          errors.push(`請求項目${index + 1}の摘要は必須項目です`);
        }
        if (item.unitPrice <= 0) {
          errors.push(`請求項目${index + 1}の単価は0より大きい値を入力してください`);
        }
        if (item.quantity <= 0) {
          errors.push(`請求項目${index + 1}の数量は0より大きい値を入力してください`);
        }
      });
    }

    // メール内容のバリデーション
    if (activeTab === 'email') {
      if (!formData.emailContent.to.trim()) {
        errors.push('宛先は必須項目です');
      }
      if (!formData.emailContent.subject.trim()) {
        errors.push('件名は必須項目です');
      }
      if (!formData.emailContent.body.trim()) {
        errors.push('本文は必須項目です');
      }
    }

    return { isValid: errors.length === 0, errors };
  };

  // 確定ボタンのクリックハンドラー
  const handleConfirmClick = () => {
    const validation = validateForm();
    
    if (!validation.isValid) {
      setErrorMessages(validation.errors);
      setShowErrorModal(true);
      return;
    }
    
    setShowFinalConfirm(true);
  };

  // モーダルを閉じる処理
  const handleClose = () => {
    // 状態をリセット
    setFormData(getInitialFormData());
    setActiveTab('billing');
    setShowFinalConfirm(false);
    setShowErrorModal(false);
    setErrorMessages([]);
    setApplicantComment('');
    setProjectSelectionMode('new');
    setShowProjectList(false);
    onClose();
  };

  if (!isOpen) return null;

  return (
    <>
      <div className="fixed inset-0 bg-black bg-opacity-50 flex items-center justify-center z-50">
        <div className="bg-white rounded-lg shadow-xl max-w-6xl w-full mx-4 max-h-[90vh] overflow-y-auto">
          <div className="px-6 py-4 border-b border-gray-200">
            <div className="flex items-center justify-between">
              <h2 className="text-xl font-semibold text-gray-900">請求書作成</h2>
              <button
                onClick={handleClose}
                className="text-gray-400 hover:text-gray-600"
              >
                <svg className="w-6 h-6" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
                </svg>
              </button>
            </div>
          </div>

          {/* タブナビゲーション */}
          <div className="px-6 pt-4">
            <div className="flex border-b border-gray-200 mb-6">
              <button
                type="button"
                onClick={() => setActiveTab('billing')}
                className={`px-4 py-2 text-sm font-medium border-b-2 ${
                  activeTab === 'billing'
                    ? 'border-blue-500 text-blue-600'
                    : 'border-transparent text-gray-500 hover:text-gray-700'
                }`}
              >
                請求内容
              </button>
              <button
                type="button"
                onClick={() => setActiveTab('email')}
                className={`px-4 py-2 text-sm font-medium border-b-2 ${
                  activeTab === 'email'
                    ? 'border-blue-500 text-blue-600'
                    : 'border-transparent text-gray-500 hover:text-gray-700'
                }`}
              >
                メール内容
              </button>
            </div>
          </div>

          <form onSubmit={handleSubmit} className="px-6 pb-4">
            {/* 請求内容タブ */}
            {activeTab === 'billing' && (
              <div className="space-y-6">
                {/* 案件情報セクション */}
                <div className="mb-6">
                  <h3 className="text-lg font-medium text-gray-900 mb-4">案件情報</h3>
                  
                  <div className="grid grid-cols-1 md:grid-cols-3 gap-4 mb-4">
                    <div>
                      <label className="block text-sm font-medium text-gray-700 mb-2">
                        案件名
                      </label>
                      <input
                        type="text"
                        value={formData.projectName}
                        className="w-full px-3 py-2 border border-gray-300 rounded-md bg-gray-50"
                        readOnly
                      />
                    </div>
                    
                    <div>
                      <label className="block text-sm font-medium text-gray-700 mb-2">
                        クライアント名
                      </label>
                      <input
                        type="text"
                        value={formData.clientName}
                        className="w-full px-3 py-2 border border-gray-300 rounded-md bg-gray-50"
                        readOnly
                      />
                    </div>
                    
                    <div>
                      <label className="block text-sm font-medium text-gray-700 mb-2">
                        担当者
                      </label>
                      <input
                        type="text"
                        value={getCurrentUser().name}
                        className="w-full px-3 py-2 border border-gray-300 rounded-md bg-gray-50"
                        readOnly
                      />
                    </div>
                  </div>
                </div>

                {/* 請求書詳細セクション */}
                <div className="mb-6">
                  <h3 className="text-lg font-medium text-gray-900 mb-4">
                    請求書詳細
                    {selectedProject && (
                      <span className="ml-2 text-sm">
                        {selectedProject.type === 'farm' && (
                          <span className="inline-flex items-center px-2 py-1 rounded-full text-xs font-medium bg-blue-100 text-blue-800">
                            ファーム案件
                          </span>
                        )}
                        {selectedProject.type === 'prime' && (
                          <span className="inline-flex items-center px-2 py-1 rounded-full text-xs font-medium bg-green-100 text-green-800">
                            プライム案件
                          </span>
                        )}
                        {selectedProject.type === 'new' && (
                          <span className="inline-flex items-center px-2 py-1 rounded-full text-xs font-medium bg-purple-100 text-purple-800">
                            新規作成
                          </span>
                        )}
                      </span>
                    )}
                  </h3>
                  
                  <div className="grid grid-cols-1 md:grid-cols-3 gap-4 mb-4">
                    <div>
                      <label className="block text-sm font-medium text-gray-700 mb-2">
                        請求書番号 <span className="text-red-500">*</span>
                        <span className="ml-2 text-xs text-gray-500">（自動生成）</span>
                      </label>
                      <input
                        type="text"
                        value={formData.billingNumber}
                        onChange={(e) => handleInputChange('billingNumber', e.target.value)}
                        placeholder="自動生成されます"
                        className="w-full px-3 py-2 border border-gray-300 rounded-md focus:outline-none focus:ring-2 focus:ring-blue-500 focus:border-blue-500 bg-gray-50"
                        required
                        readOnly
                      />
                      <p className="mt-1 text-xs text-gray-600">
                        フォーマット: YYYYMMDDSSCC
                      </p>
                    </div>
                    
                    <div>
                      <label className="block text-sm font-medium text-gray-700 mb-2">
                        請求日 <span className="text-red-500">*</span>
                      </label>
                      <input
                        type="date"
                        value={formData.billingDate}
                        onChange={(e) => handleInputChange('billingDate', e.target.value)}
                        className="w-full px-3 py-2 border border-gray-300 rounded-md focus:outline-none focus:ring-2 focus:ring-blue-500 focus:border-blue-500"
                        required
                      />
                    </div>
                    
                    <div>
                      <label className="block text-sm font-medium text-gray-700 mb-2">
                        支払期限
                      </label>
                      <input
                        type="date"
                        value={formData.dueDate}
                        onChange={(e) => handleInputChange('dueDate', e.target.value)}
                        className="w-full px-3 py-2 border border-gray-300 rounded-md focus:outline-none focus:ring-2 focus:ring-blue-500 focus:border-blue-500"
                      />
                    </div>
                  </div>
                </div>

                {/* 請求項目セクション */}
                <div className="mb-6">
                  <div className="flex items-center justify-between mb-4">
                    <h3 className="text-lg font-medium text-gray-900">請求項目</h3>
                    <button
                      type="button"
                      onClick={addBillingItem}
                      className="px-3 py-1 text-sm bg-blue-600 text-white rounded-md hover:bg-blue-700 transition-colors"
                    >
                      項目追加
                    </button>
                  </div>
                  
                  <div className="space-y-4">
                    {formData.items.map((item, index) => (
                      <div key={item.id} className="p-4 bg-gray-50 rounded-lg">
                        <div className="flex gap-4">
                          <div className="w-64">
                            <label className="block text-sm font-medium text-gray-700 mb-1">
                              摘要 <span className="text-red-500">*</span>
                            </label>
                            <input
                              type="text"
                              required
                              value={item.summary}
                              onChange={(e) => updateBillingItem(item.id, 'summary', e.target.value)}
                              className="w-full px-3 py-2 border border-gray-300 rounded-md focus:outline-none focus:ring-2 focus:ring-blue-500 focus:border-blue-500"
                              placeholder="摘要を入力"
                            />
                          </div>
                          <div className="w-36">
                            <label className="block text-sm font-medium text-gray-700 mb-1">
                              単価
                            </label>
                            <input
                              type="number"
                              value={item.unitPrice}
                              onChange={(e) => updateBillingItem(item.id, 'unitPrice', Number(e.target.value))}
                              className="w-full px-3 py-2 border border-gray-300 rounded-md focus:outline-none focus:ring-2 focus:ring-blue-500 focus:border-blue-500"
                              placeholder="0"
                            />
                          </div>
                          <div className="w-16">
                            <label className="block text-sm font-medium text-gray-700 mb-1">
                              数量
                            </label>
                            <input
                              type="number"
                              value={item.quantity}
                              onChange={(e) => updateBillingItem(item.id, 'quantity', Number(e.target.value))}
                              className="w-full px-3 py-2 border border-gray-300 rounded-md focus:outline-none focus:ring-2 focus:ring-blue-500 focus:border-blue-500"
                              placeholder="1"
                            />
                          </div>
                          <div className="w-40">
                            <label className="block text-sm font-medium text-gray-700 mb-1">
                              金額
                            </label>
                            <input
                              type="text"
                              value={formatCurrency(calculateItemAmount(item))}
                              className="w-full px-3 py-2 border border-gray-300 rounded-md bg-gray-50"
                              readOnly
                            />
                          </div>
                          <div className="flex-1 min-w-0">
                            <label className="block text-sm font-medium text-gray-700 mb-1">
                              備考
                            </label>
                            <input
                              type="text"
                              value={item.remarks}
                              onChange={(e) => updateBillingItem(item.id, 'remarks', e.target.value)}
                              className="w-full px-3 py-2 border border-gray-300 rounded-md focus:outline-none focus:ring-2 focus:ring-blue-500 focus:border-blue-500"
                              placeholder="備考"
                            />
                          </div>
                        </div>
                        {formData.items.length > 1 && (
                          <button
                            type="button"
                            onClick={() => removeBillingItem(item.id)}
                            className="mt-2 text-red-600 hover:text-red-800 text-sm"
                          >
                            削除
                          </button>
                        )}
                      </div>
                    ))}
                  </div>
                </div>

                {/* 税区分・合計セクション */}
                <div className="mb-6">
                  <h3 className="text-lg font-medium text-gray-900 mb-4">税区分・合計</h3>
                  
                  <div className="flex gap-6">
                    <div className="w-48">
                      <label className="block text-sm font-medium text-gray-700 mb-2">
                        税率(%)
                      </label>
                      <input
                        type="number"
                        value={formData.taxRate}
                        onChange={(e) => handleInputChange('taxRate', Number(e.target.value))}
                        className="w-full px-3 py-2 border border-gray-300 rounded-md focus:outline-none focus:ring-2 focus:ring-blue-500 focus:border-blue-500"
                        placeholder="10"
                      />
                    </div>
                    
                    <div className="bg-gray-50 rounded-lg p-4 flex-1">
                      <div className="space-y-3">
                        <div className="flex justify-between">
                          <span className="text-gray-600">小計:</span>
                          <span className="font-medium">{formatCurrency(calculateSubtotal())}</span>
                        </div>
                        <div className="flex justify-between">
                          <span className="text-gray-600">消費税({formData.taxRate}%):</span>
                          <span className="font-medium">{formatCurrency(calculateTaxAmount())}</span>
                        </div>
                        <div className="flex justify-between text-lg font-bold text-blue-600 border-t border-gray-200 pt-3">
                          <span>合計:</span>
                          <span>{formatCurrency(calculateTotalAmount())}</span>
                        </div>
                      </div>
                    </div>
                  </div>
                </div>

                {/* アクションボタン */}
                <div className="flex justify-end space-x-3 pt-4 border-t border-gray-200">
                  <button
                    type="button"
                    onClick={handleClose}
                    className="px-4 py-2 text-gray-700 bg-gray-100 rounded-md hover:bg-gray-200 transition-colors"
                  >
                    キャンセル
                  </button>
                  <button
                    type="button"
                    onClick={handleConfirmClick}
                    className="px-4 py-2 bg-blue-600 text-white rounded-md hover:bg-blue-700 transition-colors"
                  >
                    確定
                  </button>
                </div>
              </div>
            )}

            {/* メール内容タブ */}
            {activeTab === 'email' && (
              <div className="space-y-6">
                {/* メール内容 */}
                <div>
                  <h3 className="text-md font-medium text-gray-900 mb-4">メール内容</h3>
                  
                  <div className="space-y-4">
                    {/* 宛先 */}
                    <div>
                      <label className="block text-sm font-medium text-gray-700 mb-1">
                        宛先 <span className="text-red-500">*</span>
                      </label>
                      <input
                        type="email"
                        required
                        value={formData.emailContent.to}
                        onChange={(e) => handleInputChange('emailContent', { ...formData.emailContent, to: e.target.value })}
                        className="w-full px-3 py-2 border border-gray-300 rounded-lg focus:ring-2 focus:ring-blue-500 focus:border-blue-500"
                        placeholder="メールアドレスを入力"
                      />
                    </div>
                    
                    {/* CC と BCC を横並びで配置 */}
                    <div className="flex gap-4">
                      {/* CC */}
                      <div className="w-36">
                        <label className="block text-sm font-medium text-gray-700 mb-1">
                          CC
                        </label>
                        <input
                          type="email"
                          value={formData.emailContent.cc}
                          onChange={(e) => handleInputChange('emailContent', { ...formData.emailContent, cc: e.target.value })}
                          className="w-full px-3 py-2 border border-gray-300 rounded-lg focus:ring-2 focus:ring-blue-500 focus:border-blue-500"
                          placeholder="CCメールアドレス"
                        />
                      </div>
                      
                      {/* BCC */}
                      <div className="w-36">
                        <label className="block text-sm font-medium text-gray-700 mb-1">
                          BCC
                        </label>
                        <input
                          type="email"
                          value={formData.emailContent.bcc}
                          onChange={(e) => handleInputChange('emailContent', { ...formData.emailContent, bcc: e.target.value })}
                          className="w-full px-3 py-2 border border-gray-300 rounded-lg focus:ring-2 focus:ring-blue-500 focus:border-blue-500"
                          placeholder="BCCメールアドレス"
                        />
                      </div>
                    </div>
                    
                    {/* 件名 */}
                    <div>
                      <label className="block text-sm font-medium text-gray-700 mb-1">
                        件名 <span className="text-red-500">*</span>
                      </label>
                      <input
                        type="text"
                        required
                        value={formData.emailContent.subject}
                        onChange={(e) => handleInputChange('emailContent', { ...formData.emailContent, subject: e.target.value })}
                        className="w-full px-3 py-2 border border-gray-300 rounded-lg focus:ring-2 focus:ring-blue-500 focus:border-blue-500"
                        placeholder="メール件名を入力"
                      />
                    </div>
                    
                    {/* メール本文 */}
                    <div>
                      <label className="block text-sm font-medium text-gray-700 mb-1">
                        本文 <span className="text-red-500">*</span>
                      </label>
                      <textarea
                        value={formData.emailContent.body}
                        onChange={(e) => handleInputChange('emailContent', { ...formData.emailContent, body: e.target.value })}
                        className="w-full px-3 py-2 border border-gray-300 rounded-lg focus:ring-2 focus:ring-blue-500 focus:border-blue-500"
                        rows={6}
                        placeholder="メール本文を入力"
                        required
                      />
                    </div>
                  </div>
                </div>

                {/* アクションボタン */}
                <div className="flex justify-end space-x-3 pt-4 border-t border-gray-200">
                  <button
                    type="button"
                    onClick={() => setActiveTab('billing')}
                    className="px-4 py-2 text-gray-700 bg-gray-100 rounded-md hover:bg-gray-200 transition-colors"
                  >
                    戻る
                  </button>
                  <button
                    type="button"
                    onClick={handleConfirmClick}
                    className="px-4 py-2 bg-blue-600 text-white rounded-md hover:bg-blue-700 transition-colors"
                  >
                    確定
                  </button>
                </div>
              </div>
            )}
          </form>
        </div>
      </div>

      {/* 最終確認モーダル */}
      {showFinalConfirm && (
        <div className="fixed inset-0 bg-black bg-opacity-50 flex items-center justify-center z-50">
          <div className="bg-white rounded-lg shadow-xl max-w-2xl w-full mx-4">
            <div className="px-6 py-4 border-b border-gray-200">
              <div className="flex items-center justify-end">
                <button
                  onClick={() => setShowFinalConfirm(false)}
                  className="text-gray-400 hover:text-gray-600"
                >
                  <svg className="w-6 h-6" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                    <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
                  </svg>
                </button>
              </div>
            </div>

            <div className="px-6 py-4">
              <div className="space-y-6">
                {/* 確認メッセージ */}
                <div className="text-center">
                  <div className="mb-4">
                    <svg className="w-12 h-12 text-blue-600 mx-auto mb-3" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                      <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M9 12l2 2 4-4m6 2a9 9 0 11-18 0 9 9 0 0118 0z" />
                    </svg>
                    <h3 className="text-lg font-medium text-gray-900 mb-2">経理申請の確認</h3>
                    <p className="text-gray-600">
                      この内容で経理担当者へ申請してもよろしいですか？
                    </p>
                  </div>
                </div>

                {/* 申請者コメント */}
                <div className="border rounded-lg p-4">
                  <h3 className="font-medium text-gray-900 mb-3">申請者コメント</h3>
                  <textarea
                    value={applicantComment}
                    onChange={(e) => setApplicantComment(e.target.value)}
                    placeholder="申請に関するコメントがあれば入力してください（任意）"
                    className="w-full px-3 py-2 border border-gray-300 rounded-md focus:outline-none focus:ring-2 focus:ring-blue-500 focus:border-blue-500"
                    rows={3}
                  />
                </div>

                {/* アクションボタン */}
                <div className="flex justify-end space-x-3 pt-4 border-t border-gray-200">
                  <button
                    type="button"
                    onClick={() => setShowFinalConfirm(false)}
                    className="px-4 py-2 text-gray-700 bg-gray-100 rounded-md hover:bg-gray-200 transition-colors"
                  >
                    キャンセル
                  </button>
                  <button
                    type="button"
                    onClick={() => {
                      const billingData = {
                        ...formData,
                        totalAmount: calculateTotalAmount(),
                        subtotal: calculateSubtotal(),
                        taxAmount: calculateTaxAmount(),
                        items: formData.items.map(item => ({
                          ...item,
                          amount: calculateItemAmount(item)
                        })),
                        emailContent: generateEmailContent(),
                        applicantComment: applicantComment,
                        appliedAt: new Date().toISOString(),
                        appliedBy: getCurrentUser().name,
                        status: 'pending'
                      };
                      
                      if (onBillingApplicationComplete) {
                        onBillingApplicationComplete(billingData);
                      }
                      
                      setShowFinalConfirm(false);
                      handleClose();
                    }}
                    className="px-4 py-2 bg-green-600 text-white rounded-md hover:bg-green-700 transition-colors"
                  >
                    経理申請
                  </button>
                </div>
              </div>
            </div>
          </div>
        </div>
      )}

      {/* エラーモーダル */}
      {showErrorModal && (
        <div className="fixed inset-0 bg-black bg-opacity-50 flex items-center justify-center z-50">
          <div className="bg-white rounded-lg shadow-xl max-w-md w-full mx-4">
            <div className="px-6 py-4 border-b border-gray-200">
              <div className="flex items-center justify-between">
                <h3 className="text-lg font-medium text-gray-900">入力エラー</h3>
                <button
                  onClick={() => setShowErrorModal(false)}
                  className="text-gray-400 hover:text-gray-600"
                >
                  <svg className="w-6 h-6" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                    <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
                  </svg>
                </button>
              </div>
            </div>

            <div className="px-6 py-4">
              <div className="space-y-4">
                {/* エラーアイコン */}
                <div className="text-center">
                  <svg className="w-12 h-12 text-red-600 mx-auto mb-3" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                    <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M12 9v2m0 4h.01m-6.938 4h13.856c1.54 0 2.502-1.667 1.732-2.5L13.732 4c-.77-.833-1.964-.833-2.732 0L3.732 16.5c-.77.833.192 2.5 1.732 2.5z" />
                  </svg>
                  <p className="text-gray-600 mb-4">
                    以下の項目を入力してください：
                  </p>
                </div>

                {/* エラーメッセージ一覧 */}
                <div className="bg-red-50 border border-red-200 rounded-lg p-4">
                  <ul className="space-y-2">
                    {errorMessages.map((error, index) => (
                      <li key={index} className="text-red-700 text-sm flex items-start">
                        <span className="text-red-500 mr-2">•</span>
                        {error}
                      </li>
                    ))}
                  </ul>
                </div>

                {/* アクションボタン */}
                <div className="flex justify-end pt-4">
                  <button
                    type="button"
                    onClick={() => setShowErrorModal(false)}
                    className="px-4 py-2 bg-blue-600 text-white rounded-md hover:bg-blue-700 transition-colors"
                  >
                    閉じる
                  </button>
                </div>
              </div>
            </div>
          </div>
        </div>
      )}
    </>
  );
} 